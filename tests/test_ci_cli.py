def test_gitlab_init_check_update_cycle(make_project) -> None:
    root = make_project(GO)
    result = _quoll("ci", "init", "-y", "--platform", "gitlab", "-d", str(root))
    assert result.exit_code == 0, result.output
    assert "git add quoll.toml .gitlab-ci.yml .gitlab/ renovate.json" in result.output
    assert "Pipelines must succeed" in result.output
    assert "quoll ci schedule" in result.output  # -y skips the API: the schedule is left to do
    assert 'platform = "gitlab"' in (root / "quoll.toml").read_text()
    assert not (root / ".github").exists()
    assert _quoll("ci", "check", "-d", str(root)).exit_code == 0

    config = root / "quoll.toml"
    config.write_text(config.read_text().replace("coverage_threshold = 80", "coverage_threshold = 65"))
    assert _quoll("ci", "check", "-d", str(root)).exit_code == 1
    assert _quoll("ci", "update", "-y", "-d", str(root)).exit_code == 0
    assert "-v min=65" in (root / ".gitlab/quoll-ci.yml").read_text()


