def test_pre_commit_hooks_run_real_commands() -> None:
    """.pre-commit-hooks.yaml: each hook is a quoll command that exists and writes without asking."""
    import shlex
    from pathlib import Path

    import yaml

    hooks = yaml.safe_load((Path(__file__).parent.parent / ".pre-commit-hooks.yaml").read_text())
    assert [h["id"] for h in hooks] == ["quoll-ci", "quoll-docker", "quoll-cd"]
    for hook in hooks:
        program, *args = shlex.split(hook["entry"])
        assert program == "quoll" and hook["files"] == r"(^|/)quoll\.toml$" and not hook["pass_filenames"]
        result = _quoll(*args, "--help")
        assert result.exit_code == 0 and "--yes" in result.output
