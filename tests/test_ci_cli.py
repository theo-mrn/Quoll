class _FakeQuestion:
    def __init__(self, answer):
        self._answer = answer

    def ask(self):
        return self._answer


def _fake_questionary(monkeypatch, answers: dict) -> list:
    """Answer prompts by the first key found in the prompt message; record the messages asked."""
    import questionary

    import quoll.commands.ci as ci

    asked: list = []

    def prompt(kind):
        def _ask(message, *args, **kwargs):
            asked.append(message)
            for key, answer in answers.items():
                if key in message:
                    return _FakeQuestion(answer)
            if kind == "checkbox":  # keep the pre-checked defaults
                return _FakeQuestion([c.value for c in kwargs["choices"] if c.checked])
            return _FakeQuestion(kwargs.get("default", ""))

        return _ask

    fake = type("Q", (), {})()
    fake.Choice = questionary.Choice
    for kind in ("checkbox", "confirm", "text", "password"):
        setattr(fake, kind, prompt(kind))
    monkeypatch.setattr(ci, "questionary", fake)
    return asked


def test_interactive_init(make_project, monkeypatch) -> None:
    from quoll.ci.config import load_config

    root = make_project({**PYTHON_UV, ".env.example": "DATABASE_URL=\nDEBUG=1\n"})
    _fake_questionary(
        monkeypatch,
        {
            "Jobs": ["lint", "test", "audit", "docker", "sonar"],
            "Lint tools": ["ruff", "mypy"],
            "Minimum coverage": "70",
            "Codecov": True,
            "several versions": True,
            "Expose": ["DATABASE_URL"],
            "SonarCloud organization": "acme",
        },
    )
    result = _quoll("ci", "init", "--no-github", "-d", str(root))
    assert result.exit_code == 0, result.output

    cfg = load_config(root)
    assert cfg.lint.tools == ["ruff", "mypy"]
    assert cfg.test.coverage_threshold == 70
    assert cfg.test.codecov
    assert cfg.versions == ["3.11", "3.12", "3.13", "3.14"]
    assert cfg.test.env_secrets == ["DATABASE_URL"]
    assert cfg.security.sonar_organization == "acme"
    assert cfg.build.docker and not cfg.build.enabled


class _FakeAPI:
    def __init__(self, calls: dict) -> None:
        self.calls = calls

    def protect_branch(self, repo, branch, required_checks=(), required_reviews=1):
        self.calls["protect"] = (repo, branch, tuple(required_checks))
        return []

    def set_secrets(self, repo, secrets):
        self.calls["secrets"] = (repo, secrets)

    def ensure_schedule(self, repo, branch, cron):
        self.calls["schedule"] = (repo, branch, cron)
        return True


@pytest.mark.parametrize(
    "url, platform, host, path, checks",
    [
        ("git@github.com:acme/svc.git", "github", "github.com", "acme/svc", ("CI result",)),
        # GitLab requires the whole pipeline ("Pipelines must succeed"), not named checks.
        ("git@gitlab.acme.io:acme/team/svc.git", "gitlab", "gitlab.acme.io", "acme/team/svc", ()),
    ],
)
def test_interactive_remote_setup(make_project, monkeypatch, url, platform, host, path, checks) -> None:
    import subprocess

    from quoll import platforms
    from quoll.config.settings import settings

    root = make_project({**GO, ".env.example": "API_KEY=default-key\n"})
    subprocess.run(["git", "init", "-q", "-b", "main"], cwd=root, check=True)
    subprocess.run(["git", "remote", "add", "origin", url], cwd=root, check=True)
    _fake_questionary(monkeypatch, {"Expose": ["API_KEY"], "API_KEY (Enter": ""})
    monkeypatch.setattr(settings, f"{platform}_token", "token")
    calls: dict = {}
    target = platforms.get(platform)
    monkeypatch.setattr(target, "api", lambda h=None: calls.update(host=h) or _FakeAPI(calls))

    result = _quoll("ci", "init", "-d", str(root))
    assert result.exit_code == 0, result.output
    assert calls["host"] == host
    assert calls["protect"] == (path, "main", checks)
    # An empty answer falls back to the .env.example value.
    assert calls["secrets"] == (path, {"API_KEY": "default-key"})
    # GitLab's schedules live outside the pipeline: created through the API.
    assert calls.get("schedule") == ((path, "main", "0 6 * * 1") if platform == "gitlab" else None)


