from __future__ import annotations

import re

import pytest
from typer.testing import CliRunner

from quoll.main import app
from tests.samples import GO, PYTHON_UV

runner = CliRunner()


def _quoll(*args: str):
    return runner.invoke(app, list(args))


def test_init_yes_writes_config_and_workflows(make_project) -> None:
    root = make_project(PYTHON_UV)
    result = _quoll("ci", "init", "--yes", "--dir", str(root))
    assert result.exit_code == 0, result.output
    assert (root / "quoll.toml").exists()
    assert (root / ".github/workflows/ci.yml").exists()
    assert (root / ".github/dependabot.yml").exists()


def test_check_and_update_cycle(make_project) -> None:
    root = make_project(GO)
    assert _quoll("ci", "init", "-y", "-d", str(root)).exit_code == 0
    assert _quoll("ci", "check", "-d", str(root)).exit_code == 0

    config = root / "quoll.toml"
    config.write_text(config.read_text().replace("coverage_threshold = 80", "coverage_threshold = 65"))
    result = _quoll("ci", "check", "-d", str(root))
    assert result.exit_code == 1
    assert "out of date" in result.output

    assert _quoll("ci", "update", "-y", "-d", str(root)).exit_code == 0
    assert "min=65" in (root / ".github/workflows/ci.yml").read_text()
    assert _quoll("ci", "check", "-d", str(root)).exit_code == 0
    assert "up to date" in _quoll("ci", "update", "-y", "-d", str(root)).output


def test_init_refuses_to_overwrite_hand_written_workflow(make_project) -> None:
    root = make_project({**GO, ".github/workflows/ci.yml": "name: Mine\n"})
