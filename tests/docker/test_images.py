def test_symfony_keeps_its_env_file(make_project) -> None:
    from quoll.docker.render import render_dockerignore

    text = dockerfile(make_project, SYMFONY)
    assert "APP_ENV=prod" in text
    assert "composer run-script --no-dev post-install-cmd" in text
    root = make_project(SYMFONY)
    from quoll.docker.detect import default_config

    cfg, _ = default_config(detect(root), image_defaults(root, detect(root)))
    ignore = render_dockerignore(cfg).splitlines()
    assert ".env" not in ignore and ".env.local" in ignore


