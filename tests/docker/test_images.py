# `docker build --check` lints each Dockerfile with BuildKit (needs a Docker daemon): QUOLL_DOCKER_TESTS=check.
DOCKER_CHECK = os.environ.get("QUOLL_DOCKER_TESTS") in ("check", "build") and shutil.which("docker")


@pytest.mark.parametrize("name", list(ALL_PROJECTS))
def test_every_sample_renders(make_project, name) -> None:
    text = dockerfile(make_project, ALL_PROJECTS[name])
    assert text.startswith("# syntax=docker/dockerfile:1\n# Generated by quoll")
    # Non-root: an explicit USER, or nginx-unprivileged which already runs as nginx.
    assert "\nUSER " in text or "nginx-unprivileged" in text
    assert "\nEXPOSE " in text
    if DOCKER_CHECK:
        root = make_project(ALL_PROJECTS[name])
        (root / "Dockerfile").write_text(text)
        result = subprocess.run(["docker", "build", "--check", str(root)], capture_output=True, text=True)
        if "429 Too Many Requests" in result.stdout + result.stderr:
            pytest.skip("Docker Hub rate limit reached")
        assert result.returncode == 0 and "no warnings found" in result.stdout, result.stdout + result.stderr


