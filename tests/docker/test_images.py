def test_django_runs_gunicorn(make_project) -> None:
    files = {**DJANGO, "manage.py": "os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'shop.settings')"}
    defaults = image_defaults(make_project(files), detect(make_project(files)))
    assert defaults.command == "gunicorn shop.wsgi --bind 0.0.0.0:8000"
    assert any("gunicorn" in w for w in defaults.warnings)


def test_fastapi_finds_the_app(make_project) -> None:
    files = {
        "requirements.txt": "fastapi[standard]\n",
        "src/api/main.py": "from fastapi import FastAPI\n\napi = FastAPI()\n",
    }
    root = make_project(files)
    defaults = image_defaults(root, detect(root))
    assert defaults.command == "uvicorn api.main:api --host 0.0.0.0 --port 8000"
    assert defaults.warnings == []


def test_flask_app_factory(make_project) -> None:
    files = {"requirements.txt": "flask\ngunicorn\n", "wsgi.py": "from app import create_app\napp = create_app()\n"}
    root = make_project(files)
    assert image_defaults(root, detect(root)).command == "gunicorn wsgi:app --bind 0.0.0.0:8000"


