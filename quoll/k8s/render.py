"""Turn a K8sConfig, with the project's [docker] (port, image) and [cd] (image name), into a Helm chart.

The templates are the same for every project (quoll/k8s/chart/templates); what differs is in the values files:
values.yaml for everything, values-<environment>.yaml for what an environment changes (replicas, host)."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional

from quoll.docker.config import DockerConfig
from quoll.files import PlannedFile, header, planned
from quoll.k8s.config import Environment, K8sConfig
from quoll.yaml_dump import dump

TEMPLATES = Path(__file__).parent / "chart" / "templates"
_HELMIGNORE = "# Patterns kept out of the chart package.\n.DS_Store\n*.swp\n*.bak\n*.tmp\n"


def render_chart_yaml(k8s: K8sConfig) -> str:
    doc = {
        "apiVersion": "v2",
        "name": k8s.name,
        "description": f"{k8s.name}, generated by quoll",
        "type": "application",
        "version": "0.1.0",
        "appVersion": "latest",
    }
    return header("k8s") + dump(doc)


def render_values(
    k8s: K8sConfig, docker: DockerConfig, image: str = "", peers: Optional[Dict[str, str]] = None
) -> str:
    """values.yaml: `image` from [cd] (the deployment sets its digest), `peers` the URLs of the other projects."""
    writable = docker.image.writable_paths(docker)
    ingress: Dict[str, Any] = {"enabled": False, "className": k8s.ingress_class, "host": "", "tls": k8s.tls}
    ingress["annotations"] = {"cert-manager.io/cluster-issuer": k8s.cluster_issuer} if k8s.cluster_issuer else {}
    doc: Dict[str, Any] = {
        # The deployment sets the digest of the image it published: what was scanned and signed runs.
        "image": {"repository": image, "tag": "latest", "digest": "", "pullPolicy": "IfNotPresent"},
        "imagePullSecrets": [k8s.pull_secret] if k8s.pull_secret else [],
        "replicaCount": 1,
        "port": docker.port,
        "healthPath": k8s.health_path,
        "env": {**(peers or {}), **k8s.env},
        "envFromSecret": k8s.secret_name,
        "resources": {
            "requests": {"cpu": k8s.cpu, "memory": k8s.memory},
            "limits": {"memory": k8s.memory_limit},
        },
        # The app only writes to these directories (emptyDir volumes); null: writes in its own tree.
        "readOnlyRootFilesystem": writable is not None,
        "writablePaths": writable or [],
        "ingress": ingress,
        "autoscaling": {
            "enabled": k8s.max_replicas > 0,
            "minReplicas": 1,
            "maxReplicas": max(k8s.max_replicas, 1),
            "targetCPUUtilizationPercentage": 80,
        },
    }
    return header("k8s") + dump(doc)


def render_environment(k8s: K8sConfig, environment: Environment) -> str:
    """values-<environment>.yaml: what the environment changes."""
    doc: Dict[str, Any] = {"replicaCount": environment.replicas}
    if k8s.max_replicas:
        doc["autoscaling"] = {"minReplicas": environment.replicas}
    if environment.host:
        doc["ingress"] = {"enabled": True, "host": environment.host}
    return header("k8s") + dump(doc)


def plan(
    project_dir: Path,
    k8s: K8sConfig,
    docker: DockerConfig,
    image: str = "",
    peers: Optional[Dict[str, str]] = None,
) -> List[PlannedFile]:
    chart = Path(k8s.chart)
    files = [
        planned(project_dir, chart / "Chart.yaml", render_chart_yaml(k8s)),
        planned(project_dir, chart / "values.yaml", render_values(k8s, docker, image, peers)),
        *(
            planned(project_dir, chart / f"values-{name}.yaml", render_environment(k8s, environment))
            for name, environment in k8s.environments.items()
        ),
        planned(project_dir, chart / ".helmignore", header("k8s") + _HELMIGNORE),
    ]
    for template in sorted(TEMPLATES.iterdir()):
        files.append(planned(project_dir, chart / "templates" / template.name, template.read_text()))
    return files
