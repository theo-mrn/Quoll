def _customize(cfg: CIConfig, det: Detection, workspace: bool = False) -> CIConfig:
    data = cfg.model_dump(by_alias=True)
    # A workspace scans secrets and code once, for the whole repository (its root quoll.toml).
    repository_scans = [] if workspace else [
        questionary.Choice("Secret scanning (gitleaks)", "secrets", checked=True),
        questionary.Choice("Static analysis (Semgrep)", "sast", checked=True),
    ]
    jobs = [
        questionary.Choice("Lint", "lint", checked=cfg.lint.enabled),
        questionary.Choice(f"Tests ({cfg.test.runner or 'none detected'})", "test", checked=cfg.test.enabled),
        questionary.Choice("Dependency audit", "audit", checked=cfg.security.audit),
        *repository_scans,
        questionary.Choice(f"Build ({cfg.build.command or 'none detected'})", "build", checked=cfg.build.enabled),
        questionary.Choice("Docker image (hadolint, build, Trivy scan)", "docker", checked=det.has_dockerfile),
        *(
            [questionary.Choice("CodeQL (needs GitHub Advanced Security on private repos)", "codeql", checked=False)]
            if cfg.platform == "github" and cfg.language.ci.codeql_language
            else []
        ),
        questionary.Choice("SonarCloud", "sonar", checked=False),
    ]
    selected = ask(questionary.checkbox("Jobs", choices=jobs))

    data["lint"]["enabled"] = "lint" in selected
    if data["lint"]["enabled"]:
        known = cfg.lint_tools
        options = [t for t in cfg.lint.tools if t not in known] + known
        data["lint"]["tools"] = ask(questionary.checkbox(
            "Lint tools",
            choices=[questionary.Choice(t, t, checked=t in cfg.lint.tools) for t in options],
        ))
        data["lint"]["enabled"] = bool(data["lint"]["tools"])

    data["test"]["enabled"] = "test" in selected and bool(cfg.test.runner)
    if "test" in selected and not cfg.test.runner:
        console.print("  [yellow]No test runner detected — set test.runner in quoll.toml to enable tests.[/yellow]")
    if data["test"]["enabled"]:
        if cfg.test.coverage:
            threshold = ask(questionary.text(
                "Minimum coverage (%)",
                default=str(cfg.test.coverage_threshold),
                validate=lambda v: v.isdigit() and 0 <= int(v) <= 100 or "Enter a number between 0 and 100",
            ))
            data["test"]["coverage_threshold"] = int(threshold)
            data["test"]["codecov"] = ask(questionary.confirm("Upload coverage to Codecov?", default=False))
        if len(det.matrix_versions) > 1:
            versions = ", ".join(det.matrix_versions)
            if ask(questionary.confirm(f"Test against several versions ({versions})?", default=False)):
                data["versions"] = list(det.matrix_versions)
        if det.services:
            data["services"] = ask(questionary.checkbox(
                "Start these services for the tests",
                choices=[questionary.Choice(s, s, checked=True) for s in det.services],
            ))
        if det.env_vars:
            platform = platforms.get(cfg.platform)
            data["test"]["env_secrets"] = ask(questionary.checkbox(
                f"Expose these .env.example variables to tests (as {platform.label} {platform.secrets_label})",
                choices=[questionary.Choice(k, k, checked=True) for k in det.env_vars],
            ))

    data["security"]["audit"] = "audit" in selected
    if not workspace:
        data["security"]["secrets"] = "secrets" in selected
        data["security"]["sast"] = "sast" in selected
    data["security"]["codeql"] = "codeql" in selected
    data["security"]["sonar"] = "sonar" in selected
    if data["security"]["sonar"]:
        owner = det.remote.path.split("/")[0] if det.remote else ""
        data["security"]["sonar_organization"] = ask(questionary.text("SonarCloud organization", default=owner))
        if det.remote:
            data["security"]["sonar_project_key"] = det.remote.path.replace("/", "_")

    data["build"]["enabled"] = "build" in selected and bool(cfg.build.command)
    data["build"]["docker"] = "docker" in selected
    return CIConfig.model_validate(data)


def _remote_setup(repo: Repo, configs: List[CIConfig], det: Detection) -> None:
    platform = platforms.get(repo.platform)
    remote = det.remote
    if remote is None or platforms.hosting(remote) != platform.name:
        console.print(f"\n[dim]No {platform.label} remote (origin) found — skipping branch protection and "
                      f"{platform.secrets_label}.[/dim]")
        return
    branch = repo.branches[0]

    protect = ask(questionary.confirm(
        f"Require the pipeline to pass before merging into {remote.path}@{branch}?", default=True
    ))

    secrets: Dict[str, str] = {}
    wanted: List[str] = list(dict.fromkeys(s for cfg in configs for s in cfg.test.env_secrets))
    if any(cfg.security.sonar for cfg in configs):
        wanted.append("SONAR_TOKEN")
    if any(cfg.test.codecov for cfg in configs):
        wanted.append("CODECOV_TOKEN")
    if wanted and ask(questionary.confirm(
        f"Set the {platform.label} {platform.secrets_label} now ({', '.join(wanted)})?", default=True
    )):
        for key in wanted:
            default = det.env_vars.get(key, "")
            value = ask(questionary.password(f"{key}" + (" (Enter = .env.example value)" if default else "")))
            if value or default:
                secrets[key] = value or default

    schedule = repo.schedule.enabled and platform.schedules_via_api and ask(questionary.confirm(
        f"Schedule the security scans ({repo.schedule.cron}, UTC) on {branch}?", default=True
    ))

    if not protect and not secrets and not schedule:
        return
    if not ensure_token(platform.name, remote.host):
        console.print(f"[yellow]No {platform.label} token — skipped.[/yellow]")
        return

    api = platform.api(remote.host)
    if protect:
        try:
            for warning in api.protect_branch(remote.path, branch, required_checks=platform.required_checks):
                console.print(f"[yellow]Warning:[/yellow] {warning}")
            console.print(f"[green]✓[/green] {branch} is protected: merges require a green pipeline")
        except PlatformError as e:
            console.print(f"[yellow]Warning:[/yellow] branch protection failed: {e}")
    if schedule:
        _schedule(api, remote.path, branch, repo.schedule.cron)
    if secrets:
        try:
            api.set_secrets(remote.path, secrets)
            console.print(f"[green]✓[/green] {len(secrets)} {platform.secrets_label} set: {', '.join(secrets)}")
        except Exception as e:  # httpx errors, missing PyNaCl...
            console.print(f"[yellow]Warning:[/yellow] setting {platform.secrets_label} failed: {e}")


def _schedule(api: PlatformAPI, repo: str, branch: str, cron: str) -> None:
    try:
        api.ensure_schedule(repo, branch, cron)
        console.print(f"[green]✓[/green] Security scans scheduled on {branch} ({cron}, UTC)")
    except PlatformError as e:
        console.print(f"[yellow]Warning:[/yellow] scheduling the security scans failed: {e}")


# --------------------------------------------------------------------------- output


def _print_detection(det: Detection) -> None:
    table = Table(show_header=False, box=None, padding=(0, 2))
    table.add_column(style="dim")
    table.add_column(style="bold")
    version = f"{det.version} (from {det.version_file})" if det.version_file else det.version
    table.add_row("Stack", det.stack or "-")
    table.add_row("Framework", det.framework or "-")
    table.add_row("Package manager", det.package_manager + (f" ({det.lockfile})" if det.lockfile else ""))
    table.add_row("Version", version)
    table.add_row("Lint", ", ".join(det.lint_tools) or "-")
    table.add_row("Tests", det.test_runner + ("" if det.coverage or not det.test_runner else " (no coverage)") or "-")
    table.add_row("Build", det.build_command.replace("\n", " && ") or "-")
    table.add_row("Services", ", ".join(det.services) or "-")
    table.add_row("Dockerfile", "yes" if det.has_dockerfile else "no")
    table.add_row("Default branch", det.default_branch)
    remote = f" ({det.remote.host}/{det.remote.path})" if det.remote else ""
    table.add_row("Platform", platforms.get(det.platform).label + remote)
    console.print(table)
    for warning in det.warnings:
        console.print(f"[yellow]![/yellow] {warning}")
    console.print()


# --------------------------------------------------------------------------- helpers


def _plan(root: Path, target: Union[CIConfig, Repo]) -> list:
    platform = target.platform
    try:
        return platforms.get(platform).ci_files(root, target)
    except ValueError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)


def _repo(project_dir: Path) -> Tuple[Path, Repo]:
    """The repository `project_dir` belongs to (its workspace root, if any) and its pipeline settings."""
    root = find_root(project_dir)
    try:
        return root, load_repo(root)
    except ConfigError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)


def _configured(project_dir: Path) -> bool:
    try:
        data = quoll_toml.read(project_dir)
    except ConfigError:
        return True
    return "ci" in data or "workspace" in data
