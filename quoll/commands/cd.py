from __future__ import annotations

from pathlib import Path
from typing import List, Optional, Union

import questionary
import typer
from rich.table import Table

from quoll import platforms
from quoll.cd.config import CONFIG_FILE, CDConfig, ConfigError, save_config
from quoll.ci.detect import configured_platform, default_branch
from quoll.commands._common import (
    DirOption,
    ask,
    check_files,
    check_platform,
    confirm_overwrite,
    platform_option,
    resolve_dir,
    update_files,
)
from quoll.config import quoll_toml
from quoll.console import console
from quoll.files import PlannedFile, write
from quoll.platforms.gitlab.ci import CD_PATH, PIPELINE_PATH
from quoll.workspace import Delivery, find_root, load_deliveries, load_workspace, member_name

app = typer.Typer(help="Generate and maintain the delivery pipeline: build, scan, push.", no_args_is_help=True)


@app.command()
def init(
    project_dir: Path = DirOption,
    yes: bool = typer.Option(False, "--yes", "-y", help="Accept the defaults without asking."),
    force: bool = typer.Option(False, "--force", help="Overwrite a pipeline that was not generated by quoll."),
    platform: Optional[str] = platform_option(),
    registry: Optional[str] = typer.Option(
        None, help="ghcr (GitHub) or gitlab (GitLab) — the default —, or dockerhub."
    ),
    image: Optional[str] = typer.Option(None, help="Image name, e.g. ghcr.io/acme/api."),
    release_pr: Optional[bool] = typer.Option(
        None, "--release-pr/--no-release-pr",
        help="GitHub: a release PR from the Conventional Commits (release-please) tags the releases (default: yes).",
    ),
) -> None:
    """Write [cd] in quoll.toml and generate the delivery pipeline.

    At the root of a workspace: for each of its projects with a Dockerfile; in one of its projects: for it."""
    project_dir = resolve_dir(project_dir)
    check_platform(platform)
    root = find_root(project_dir)
    try:
        workspace = load_workspace(root)
    except ConfigError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)
    if workspace is None:
        cfg = _configure(project_dir, root, "", yes=yes, force=force, platform=platform, registry=registry,
                         image=image, release_pr=release_pr)
        if cfg is None:
            raise typer.Exit(0)
        deliveries: List[Delivery] = [Delivery("", ".", cfg)]
    else:
        if project_dir == root:
            members = [m for m in workspace.members if (root / m / "Dockerfile").exists()]
            for m in workspace.members:
                if m not in members:
                    console.print(f"[yellow]![/yellow] {m}: no Dockerfile — run [bold]quoll docker init[/bold] first.")
        else:
            members = [project_dir.relative_to(root).as_posix()]
        if image and len(members) > 1:
            console.print("[red]Error:[/red] --image names one image: run `quoll cd init` in each project directory.")
            raise typer.Exit(1)
        for member in members:
            _configure(root / member, root, member_name(member), yes=yes, force=force, platform=platform,
                       registry=registry, image=image, release_pr=release_pr)
            # A workspace releases as a whole: asked once.
            if release_pr is None:
                release_pr = _read(root / member).get("cd", {}).get("release_pr", False)
        deliveries = _deliveries(root)

    cfg = deliveries[0].cfg
    files = _writable(_plan(root, deliveries))
    if not confirm_overwrite(files, yes=yes, force=force):
        raise typer.Exit(1)
    for delivery in deliveries:
        save_config(root / delivery.directory, delivery.cfg)
    write(root, files)
    console.print()
    for f in files:
        console.print(f"[green]✓[/green] {f.path}")

    for delivery in deliveries:
        console.print(f"\n[bold green]Done![/bold green] Every push to {', '.join(delivery.cfg.branches)} and every v* "
                      f"tag now publishes {delivery.cfg.image}.")
    target = platforms.get(cfg.platform)
    secrets = sorted({s for d in deliveries for s in target.registry_secrets(d.cfg.registry)})
    if secrets:
        names = " and ".join(f"[bold]{s}[/bold]" for s in secrets)
        console.print(f"Set the {names} {target.label} {target.secrets_label}.")
    if cfg.platform == "gitlab":
        _check_gitlab_include(root)
    if any(d.cfg.release_pr for d in deliveries):
        console.print(RELEASE_NOTE)


RELEASE_NOTE = (
    "\nReleases: commit with Conventional Commits ([bold]feat:[/bold], [bold]fix:[/bold], [bold]feat!:[/bold]); "
    "release-please keeps a release PR open, and merging it tags the version, which publishes and deploys.\n"
    "GitHub must let Actions open pull requests: Settings → Actions → General → "
    "[bold]Allow GitHub Actions to create and approve pull requests[/bold] (`quoll new --remote` turns it on)."
)


def _configure(
    project_dir: Path,
    root: Path,
    member: str,
    *,
    yes: bool,
    force: bool,
    platform: Optional[str],
    registry: Optional[str],
    image: Optional[str],
    release_pr: Optional[bool] = None,
) -> Optional[CDConfig]:
    """The [cd] of one project, asked or defaulted; saved in its quoll.toml. None when kept as it was."""
    console.print(f"\n[bold]quoll cd[/bold] — {member or project_dir.name}\n")
    if "cd" in _read(project_dir) and not force:
        if yes or not ask(questionary.confirm(f"{CONFIG_FILE} already configures CD. Replace it?", default=False)):
            console.print("Kept. Use [bold]quoll cd update[/bold] to regenerate from quoll.toml.")
            return None
    if not (project_dir / "Dockerfile").exists():
        console.print("[yellow]![/yellow] No Dockerfile yet — run [bold]quoll docker init[/bold] first.")

    remote = platforms.remote(root)
    name = platform or configured_platform(project_dir) or configured_platform(root) or platforms.detect(root, remote)
    target = platforms.get(name)
    registries = target.registries
    if registry is None:
        registry = registries[0] if yes else ask(
            questionary.select("Registry", choices=list(registries), default=registries[0])
        )
    if registry not in registries:
        console.print(
            f"[red]Error:[/red] unknown registry '{registry}' for {target.label} "
            f"(expected one of: {', '.join(registries)})."
        )
        raise typer.Exit(1)
    default_image = target.default_image(remote, registry, root.name, member)
    if image is None:
        image = default_image if yes else ask(questionary.text("Image", default=default_image))

    note = " (private GitHub repositories need GitHub Enterprise Cloud)" if name == "github" else ""
    sign = True if yes else ask(questionary.confirm(f"Sign the image and its SBOM with Sigstore{note}?", default=True))
    if name != "github":
        release_pr = False
    elif release_pr is None:
        release_pr = True if yes else ask(questionary.confirm(
            "Open a release PR from the Conventional Commits (release-please)? Merging it tags the version.",
            default=True,
        ))

    try:
        cfg = CDConfig(
            platform=name, registry=registry, image=image.lower(), branches=[default_branch(root)], sign=sign,
            release_pr=release_pr,
        )
    except ValueError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)
    _print_config(cfg)
    if member:
        save_config(project_dir, cfg)
    return cfg


@app.command()
def update(
    project_dir: Path = DirOption,
    yes: bool = typer.Option(False, "--yes", "-y", help="Write changes without asking."),
    force: bool = typer.Option(False, "--force", help="Overwrite a pipeline that was not generated by quoll."),
) -> None:
    """Regenerate the delivery workflow from quoll.toml (the workspace's, from any of its directories)."""
    root = find_root(resolve_dir(project_dir))
    update_files(root, _writable(_plan(root, _deliveries(root))), yes=yes, force=force, what="CD is")


@app.command()
def check(project_dir: Path = DirOption) -> None:
    """Fail if the delivery pipeline differs from what quoll.toml describes."""
    root = find_root(resolve_dir(project_dir))
    check_files([f for f in _plan(root, _deliveries(root)) if not f.create_only], "cd")


def _plan(root: Path, deliveries: List[Delivery]) -> List[PlannedFile]:
    target: Union[CDConfig, List[Delivery]] = deliveries[0].cfg if not deliveries[0].name else deliveries
    return platforms.get(deliveries[0].cfg.platform).cd_files(root, target)


def _writable(files: List[PlannedFile]) -> List[PlannedFile]:
    """Without release-please's configuration and manifest once written: they are the project's then."""
    return [f for f in files if not (f.create_only and f.existing is not None)]


def _deliveries(root: Path) -> List[Delivery]:
    try:
        return load_deliveries(root)
    except ConfigError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)


def _check_gitlab_include(project_dir: Path) -> None:
    """.gitlab/cd.yml only runs when .gitlab-ci.yml includes it, as quoll's does."""
    pipeline = project_dir / PIPELINE_PATH
    if pipeline.exists() and CD_PATH in pipeline.read_text():
        return
    if not pipeline.exists():
        console.print("[yellow]![/yellow] No .gitlab-ci.yml yet — run [bold]quoll ci init[/bold], which includes "
                      f"{CD_PATH}.")
    else:
        console.print(f"[yellow]![/yellow] Add {CD_PATH} to your .gitlab-ci.yml (and a `publish` stage after the "
                      f"tests):\n  include:\n    - local: {CD_PATH}")


def _print_config(cfg: CDConfig) -> None:
    table = Table(show_header=False, box=None, padding=(0, 2))
    table.add_column(style="dim")
    table.add_column(style="bold")
    table.add_row("Image", cfg.image)
    table.add_row("Published on", ", ".join([*cfg.branches, *(["v* tags"] if cfg.release_tags else [])]))
    table.add_row("Scan", f"Trivy, blocks on {', '.join(cfg.severity)}" if cfg.scan else "off")
    table.add_row("Platforms", ", ".join(cfg.platforms))
    table.add_row("SBOM", "artifact + release asset" if cfg.sbom else "off")
    table.add_row("Signature", "Sigstore" if cfg.sign else "off")
    if cfg.platform == "github":
        table.add_row("Releases", "release PR (release-please)" if cfg.release_pr else "v* tags pushed by hand")
    console.print(table)


def _read(project_dir: Path) -> dict:
    try:
        return quoll_toml.read(project_dir)
    except ConfigError:
        return {}
