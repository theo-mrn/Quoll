"""Helpers shared by the commands (`quoll ci`, `quoll docker`, `quoll cd`...)."""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import Any, List, Optional

import questionary
import typer
from rich.syntax import Syntax

from quoll import languages, platforms
from quoll.config.quoll_toml import CONFIG_FILE
from quoll.config.settings import settings
from quoll.config.store import load_stored_token, save_token
from quoll.console import console
from quoll.files import PlannedFile, write

DirOption = typer.Option(Path("."), "--dir", "-d", help="Project directory.")

# CLI of each platform that can hand over its token: `gh auth token`, `glab config get token`.
_CLI_TOKEN = {
    "github": lambda host: ["gh", "auth", "token"],
    "gitlab": lambda host: ["glab", "config", "get", "token", "--host", host or "gitlab.com"],
}


def platform_option() -> Any:
    return typer.Option(
        None, "--platform", help=f"{' or '.join(platforms.NAMES)} (default: detected from the git remote)."
    )


def check_platform(name: Optional[str]) -> None:
    if name is not None and name not in platforms.NAMES:
        console.print(f"[red]Error:[/red] unknown platform '{name}' (expected one of: {', '.join(platforms.NAMES)}).")
        raise typer.Exit(1)


def ensure_token(platform: str, host: Optional[str] = None) -> bool:
    """A token for `platform` in settings: from the environment, ~/.config/quoll, the platform's CLI, or asked."""
    attr = f"{platform}_token"
    if getattr(settings, attr):
        return True
    token = load_stored_token(platform) or _cli_token(platform, host)
    if not token:
        label = platforms.get(platform).label
        scope = "repo" if platform == "github" else "api"
        token = ask(questionary.password(f"{label} token ({scope} scope)"))
        if not token:
            return False
        save_token(token, platform)
        console.print("[dim]Token saved to ~/.config/quoll/config.toml[/dim]")
    setattr(settings, attr, token)
    return True


def _cli_token(platform: str, host: Optional[str]) -> str:
    command = _CLI_TOKEN[platform](host)
    if not shutil.which(command[0]):
        return ""
    try:
        result = subprocess.run(command, capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return ""
    return result.stdout.strip() if result.returncode == 0 else ""


def resolve_dir(project_dir: Path) -> Path:
    project_dir = project_dir.resolve()
    if not project_dir.is_dir():
        console.print(f"[red]Error:[/red] '{project_dir}' is not a directory.")
        raise typer.Exit(1)
    return project_dir


def ask(question: Any) -> Any:
    answer = question.ask()
    if answer is None:  # Ctrl-C
        raise typer.Exit(130)
    return answer


def supported_hint() -> str:
    lines = [f"  {lang.name}: {', '.join(lang.markers)}" for lang in languages.available()]
    return "Supported languages (detected from these files):\n" + "\n".join(lines)


def print_diff(f: PlannedFile) -> None:
    diff = f.diff()
    if diff:
        console.print(Syntax(diff, "diff", theme="ansi_dark", background_color="default", word_wrap=True))


def confirm_overwrite(files: List[PlannedFile], *, yes: bool, force: bool, already_shown: bool = False) -> bool:
    """Refuse to replace hand-written files unless --force or the user agrees."""
    for f in files:
        if f.existing is None or not f.changed:
            continue
        if not f.managed and not force:
            console.print(f"\n[yellow]![/yellow] {f.path} exists and was not generated by quoll.")
            if yes:
                console.print("  Re-run with [bold]--force[/bold] to replace it.")
                return False
            if not already_shown:
                print_diff(f)
            if not ask(questionary.confirm(f"Replace {f.path}?", default=False)):
                return False
    return True


def update_files(project_dir: Path, files: List[PlannedFile], *, yes: bool, force: bool, what: str) -> None:
    """Show the diff of the changed files, confirm, write them."""
    changed = [f for f in files if f.changed]
    if not changed:
        console.print(f"[green]✓[/green] {what} up to date.")
        return
    for f in changed:
        print_diff(f)
    if not confirm_overwrite(changed, yes=yes, force=force, already_shown=True):
        raise typer.Exit(1)
    if not yes and not ask(questionary.confirm("Write these changes?", default=True)):
        raise typer.Exit(1)
    write(project_dir, changed)
    for f in changed:
        console.print(f"[green]✓[/green] {f.path} updated")


def check_files(files: List[PlannedFile], command: str) -> None:
    """Exit 1 when a file is missing or differs from quoll.toml."""
    stale = False
    for f in files:
        if f.existing is None:
            console.print(f"[red]✗[/red] {f.path} is missing. Run [bold]quoll {command} update[/bold].")
            stale = True
        elif f.changed:
            print_diff(f)
            console.print(f"[red]✗[/red] {f.path} is out of date. Run [bold]quoll {command} update[/bold].")
            stale = True
        else:
            console.print(f"[green]✓[/green] {f.path} matches {CONFIG_FILE}.")
    if stale:
        raise typer.Exit(1)
