app = typer.Typer(help="Generate and maintain the Dockerfile of a project.", no_args_is_help=True)


@app.command()
def init(
    project_dir: Path = DirOption,
    yes: bool = typer.Option(False, "--yes", "-y", help="Accept detected defaults without asking."),
    force: bool = typer.Option(False, "--force", help="Overwrite a Dockerfile that was not generated by quoll."),
    command: str = typer.Option("", "--command", help="What the container runs, when quoll can't infer it."),
) -> None:
    """Detect the project, write quoll.toml and generate a Dockerfile, .dockerignore and compose.yaml.

    At the root of a workspace: for each of its projects."""
    project_dir = resolve_dir(project_dir)
    members = _members(project_dir)
    if members is None:
        _init(project_dir, yes=yes, force=force, command=command)
        return
    for member in members:
        if force or "docker" not in _read(project_dir / member):
            _init(project_dir / member, yes=yes, force=force, command=command, label=member)
    files = _workspace_files(project_dir)
    if files and confirm_overwrite(files, yes=yes, force=force):
        write(project_dir, files)
        console.print(f"\n[green]✓[/green] {files[0].path} (the whole workspace)")
        console.print("\n[bold green]Done![/bold green] Run every project and its services:")
        console.print("  docker compose up --build")


def _init(project_dir: Path, *, yes: bool, force: bool, command: str, label: str = "") -> None:
    console.print(f"\n[bold]quoll docker[/bold] — {label or project_dir.name}\n")

    if "docker" in _read(project_dir) and not force:
        if yes or not ask(questionary.confirm(
            f"{CONFIG_FILE} already configures Docker. Detect again and replace it?", default=False
        )):
            console.print("Nothing changed. Use [bold]quoll docker update[/bold] to regenerate from quoll.toml.")
            raise typer.Exit(0)

    det = detect(project_dir)
    if det.stack is None:
        console.print(f"[red]Error:[/red] no supported project found.\n{supported_hint()}")
        raise typer.Exit(1)
    try:
        defaults = image_defaults(project_dir, det)
    except ValueError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)
    if command:
        defaults.command = command
    _print_defaults(det, defaults)

    if not yes:
        _customize(defaults, det)
    elif _needs_command(det, defaults) and not defaults.command:
        console.print("[red]Error:[/red] quoll couldn't infer what the container runs. Pass [bold]--command[/bold].")
        raise typer.Exit(1)

    cfg = default_config(det, defaults)[0]
    files = render.plan(project_dir, cfg)
    if not confirm_overwrite(files, yes=yes, force=force):
        raise typer.Exit(1)

    save_config(project_dir, cfg)
    write(project_dir, files)
    console.print()
    console.print(f"[green]✓[/green] {CONFIG_FILE}")
    for f in files:
        console.print(f"[green]✓[/green] {f.path}")

    console.print("\n[bold green]Done![/bold green] Run the app" + (" and its services:" if cfg.services else ":"))
    console.print("  docker compose up --build")
    _suggest_ci_build(project_dir)


@app.command()
def update(
    project_dir: Path = DirOption,
    yes: bool = typer.Option(False, "--yes", "-y", help="Write changes without asking."),
    force: bool = typer.Option(False, "--force", help="Overwrite a Dockerfile that was not generated by quoll."),
) -> None:
    """Regenerate the Dockerfile, .dockerignore and compose.yaml from quoll.toml (each project's, in a
    workspace)."""
    project_dir = resolve_dir(project_dir)
    for directory in _targets(project_dir):
        files = render.plan(directory, _load(directory))
        update_files(directory, files, yes=yes, force=force, what=f"Docker files of {directory.name} are")
    root = find_root(project_dir)
    files = _workspace_files(root)
    if files:
        update_files(root, files, yes=yes, force=force, what="The workspace's compose.yaml is")


@app.command()
def check(project_dir: Path = DirOption) -> None:
    """Fail if the Docker files differ from what quoll.toml describes (each project's, in a workspace)."""
    project_dir = resolve_dir(project_dir)
    for directory in _targets(project_dir):
        check_files(render.plan(directory, _load(directory)), "docker")
    root = find_root(project_dir)
    files = _workspace_files(root)
    if files:
        check_files(files, "docker")


def _workspace_files(root: Path) -> list:
    """The compose.yaml running a whole workspace (its projects with a [docker] section), if `root` is one."""
    members = _members(root)
    if not members:
        return []
    configs = [(member_name(m), m, _load(root / m)) for m in members if "docker" in _read(root / m)]
    return render.plan_workspace(root, configs) if configs else []


def _members(project_dir: Path) -> Optional[List[str]]:
    """The projects of the workspace whose root is `project_dir`, or None."""
    try:
        workspace = load_workspace(project_dir)
    except ConfigError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)
    return workspace.members if workspace else None


def _targets(project_dir: Path) -> List[Path]:
    """`project_dir`, or the workspace projects with a [docker] section when it is a workspace root."""
    members = _members(project_dir)
    if members is None:
        return [project_dir]
    targets = [project_dir / m for m in members if "docker" in _read(project_dir / m)]
    if not targets:
        console.print("[red]Error:[/red] no project of the workspace has a [docker] section. Run "
                      "[bold]quoll docker init[/bold] first.")
        raise typer.Exit(1)
    return targets


# --------------------------------------------------------------------------- interactive


def _customize(defaults: DockerDefaults, det: Detection) -> None:
    port = ask(questionary.text(
        "Port the app listens on",
        default=str(defaults.port),
        validate=lambda v: v.isdigit() and 0 < int(v) < 65536 or "Enter a port number",
    ))
    defaults.port = int(port)
    if _needs_command(det, defaults):
        defaults.command = ask(questionary.text(
            "Command the container runs",
            default=defaults.command,
            validate=lambda v: bool(v.strip()) or "The container needs a command",
        )).strip()


def _needs_command(det: Detection, defaults: DockerDefaults) -> bool:
    if defaults.static:
        return False
    image = languages.docker_image(det.stack, det.framework)
    return image is not None and image.requires_command


# --------------------------------------------------------------------------- output


def _print_defaults(det: Detection, defaults: DockerDefaults) -> None:
    table = Table(show_header=False, box=None, padding=(0, 2))
    table.add_column(style="dim")
    table.add_column(style="bold")
    table.add_row("Stack", det.stack + (f" / {det.framework}" if det.framework else ""))
    table.add_row("Version", det.version)
    table.add_row("Build", defaults.build_command or "-")
    if defaults.static:
        table.add_row("Serves", f"{defaults.output_dir}/ (static, nginx)")
    else:
        table.add_row("Runs", defaults.command or "[yellow]?[/yellow]")
    table.add_row("Port", str(defaults.port))
    table.add_row("Services", ", ".join(det.services) or "-")
    table.add_row("Existing Dockerfile", "yes" if det.has_dockerfile else "no")
    console.print(table)
    for warning in [*det.warnings, *defaults.warnings]:
        console.print(f"[yellow]![/yellow] {warning}")
    console.print()


def _suggest_ci_build(project_dir: Path) -> None:
    try:
        ci = load_ci_config(project_dir)
    except CIConfigError:
        return
    if not ci.build.docker:
        console.print(
            "\n[dim]To build the image in CI: set [bold]build.docker = true[/bold] in [ci], "
            "then run [bold]quoll ci update[/bold].[/dim]"
        )


# --------------------------------------------------------------------------- helpers


def _read(project_dir: Path) -> dict:
    try:
        return quoll_toml.read(project_dir)
    except ConfigError:
        return {}


def _load(project_dir: Path) -> DockerConfig:
    try:
        return load_config(project_dir)
    except ConfigError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(1)
