from __future__ import annotations

from typing import TYPE_CHECKING, Any, Dict, List

from quoll.languages.base import Detection, DockerDefaults
from quoll.languages.ruby.detect import has_gem
from quoll.languages.ruby.docker import RubyImage
from quoll.project import Project

if TYPE_CHECKING:
    from quoll.docker.config import DockerConfig


class RailsImage(RubyImage):
    def defaults(self, project: Project, det: Detection) -> DockerDefaults:
        warnings = []
        if project.exists("package.json") and not has_gem(project, "importmap-rails"):
            warnings.append("Assets built with Node (jsbundling/cssbundling) are not built by this image yet.")
        return DockerDefaults(port=3000, command="./bin/rails server -b 0.0.0.0 -p 3000", warnings=warnings)

    def context(self, project: Project, cfg: DockerConfig) -> Dict[str, Any]:
        context = super().context(project, cfg)
        bootsnap = has_gem(project, "bootsnap")
        bundle_install = [
            "bundle install",
            'rm -rf ~/.bundle/ "${BUNDLE_PATH}"/ruby/*/cache "${BUNDLE_PATH}"/ruby/*/bundler/gems/*/.git',
        ]
        after_copy = []
        if bootsnap:
            bundle_install.append("bundle exec bootsnap precompile --gemfile")
            after_copy.append("bundle exec bootsnap precompile app/ lib/")
        if has_gem(project, "propshaft") or has_gem(project, "sprockets-rails"):
            # The production secret isn't needed to compile assets.
            after_copy.append("SECRET_KEY_BASE_DUMMY=1 ./bin/rails assets:precompile")
        return {
            **context,
            "workdir": "/rails",
            "env": {"RAILS_ENV": "production", "BUNDLE_DEPLOYMENT": "1", **context["env"]},
            "bundle_install": bundle_install,
            "after_copy": after_copy,
            # Generated by Rails 7.1+.
            "entrypoint": project.exists("bin/docker-entrypoint"),
        }

    def dockerignore(self, cfg: DockerConfig) -> List[str]:
        return [
            "log/*",
            "!log/.keep",
            "tmp/*",
            "!tmp/.keep",
            "storage/*",
            "!storage/.keep",
            "node_modules",
            "public/assets",
            "app/assets/builds/*",
            "!app/assets/builds/.keep",
            "config/master.key",
            "config/credentials/*.key",
            ".env",
            ".env.*",
            "!.env.example",
        ]
